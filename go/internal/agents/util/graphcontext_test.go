// Non-dict entries inside "nodes"/"edges" are skipped by the isinstance guards,
// but the COUNTS in the stats block come from the raw lists, so the two
// disagree on purpose.
func TestBuildGraphContext_NonDictEntriesAreSkippedButStillCounted(t *testing.T) {
	dir := t.TempDir()
	graph := filepath.Join(dir, "graph.json")
	writeFile(t, graph, `{"nodes": ["oops", {"resource_id": "a", "resource_type": "aws_iam_role"}],
	                      "edges": [42, {"source": "a", "target": "b"}]}`)

	summary, stats, edges := BuildGraphContextForHunter(graph, fixtureAbsent, []string{"iam"})
	mustContain(t, "summary", summary, "  - a (aws_iam_role) @ None")
	mustNotContain(t, "summary", summary, "oops")
	mustContain(t, "edges", edges, "  - a --[references]--> b")
	mustContain(t, "stats", stats, "Graph nodes: 2")
	mustContain(t, "stats", stats, "Graph edges: 2")
	mustContain(t, "stats", stats, "Filtered nodes: 1")
	mustContain(t, "stats", stats, "Filtered edges: 1")
}

