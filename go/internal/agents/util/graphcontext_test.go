// The two id lookups use DIFFERENT defaults: all_nodes_by_id keys on
// node.get("resource_id", "") while relevant_node_ids collects
// node.get("resource_id") — Python None. An id-less node therefore lands under
// "" in the map and under None in the set, and an edge with no "source" reads
// as None in the relevance filter but as "" in the neighbor loop. The observable
// consequence: the id-less node is pulled in as its own 1-hop neighbor.
func TestBuildGraphContext_MissingIDDefaultsDifferInTheMapAndTheSet(t *testing.T) {
	dir := t.TempDir()
	graph := filepath.Join(dir, "graph.json")
	writeFile(t, graph, `{"nodes": [{"resource_type": "aws_iam_role", "file_path": "iam.tf"}],
	                      "edges": [{"target": "unrelated"}]}`)

	summary, stats, edges := BuildGraphContextForHunter(graph, fixtureAbsent, []string{"iam"})
	// The edge has no "source": edge.get("source") is None, which IS in
	// relevant_node_ids, so the edge is relevant.
	mustContain(t, "stats", stats, "Filtered edges: 1")
	mustContain(t, "edges", edges, "  - None --[references]--> unrelated")
	// In the neighbor loop the same endpoint reads as "" (not in the set), and
	// "" IS a key of all_nodes_by_id — so the node reappears as a neighbor.
	mustContain(t, "summary", summary, "CONNECTED RESOURCES (1-hop neighbors):")
	if got := strings.Count(summary, "  - None (aws_iam_role) @ iam.tf"); got != 2 {
		t.Errorf("expected the id-less node listed twice (relevant + neighbor), got %d\n%s", got, summary)
	}
}

