// The committed fixture pair, mirrored into internal/agents/hunt/testdata by
// go/scripts/gen_golden.py. See that script's GRAPH_CONTEXT_CASES for the
// Python side of every golden asserted here.
const (
	fixtureGraph       = "testdata/fixture/graph.json"
	fixtureInventory   = "testdata/fixture/inventory.json"
	fixtureNotAnObject = "testdata/fixture/not_an_object.json"
	fixtureAbsent      = "testdata/fixture/absent.json" // deliberately does not exist
)

func readGolden(t *testing.T, name string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("testdata", "golden", name))
	if err != nil {
		t.Fatalf("reading golden %s: %v (regenerate with go/scripts/gen_golden.py)", name, err)
	}
	return string(b)
}

// TestBuildGraphContextForHunter_MatchesThePythonGoldens is the byte-for-byte
// parity gate: every case here is generated by driving the REAL Python
// build_graph_context_for_hunter over the same committed fixture (see
// GRAPH_CONTEXT_CASES in go/scripts/gen_golden.py), so a golden can only move
// when the Python function moves.
func TestBuildGraphContextForHunter_MatchesThePythonGoldens(t *testing.T) {
	cases := []struct {
		name      string
		graph     string
		inventory string
		keywords  []string
	}{
		{"iam", fixtureGraph, fixtureInventory, []string{"iam", "role", "policy"}},
		{"data", fixtureGraph, fixtureInventory, []string{"s3", "bucket", "kms"}},
		{"all", fixtureGraph, fixtureInventory, []string{""}},
		{"nomatch", fixtureGraph, fixtureInventory, []string{"nonexistent_type_xyz"}},
		{"missing_files", fixtureAbsent, fixtureAbsent, []string{"iam"}},
		{"not_an_object", fixtureNotAnObject, fixtureNotAnObject, []string{"iam"}},
	}

	for _, tc := range cases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			nodes, stats, edges := BuildGraphContextForHunter(tc.graph, tc.inventory, tc.keywords)
			for _, part := range []struct {
				label, got, golden string
			}{
				{"nodes", nodes, tc.name + "_nodes.txt"},
				{"stats", stats, tc.name + "_stats.txt"},
				{"edges", edges, tc.name + "_edges.txt"},
			} {
				if want := readGolden(t, part.golden); part.got != want {
					t.Errorf("%s block differs from Python\n--- got ---\n%s\n--- want ---\n%s",
						part.label, part.got, want)
				}
			}
		})
	}
}

