// The neighbor block is the one place Python iterates a set. Go emits
// first-encounter order; assert it is STABLE and follows the edge scan
// (source before target, edges in document order).
func TestBuildGraphContext_NeighborOrderIsDeterministic(t *testing.T) {
	dir := t.TempDir()
	graph := filepath.Join(dir, "graph.json")
	writeFile(t, graph, `{"nodes": [
	    {"resource_id": "hub", "resource_type": "aws_iam_role"},
	    {"resource_id": "zeta", "resource_type": "aws_s3_bucket"},
	    {"resource_id": "alpha", "resource_type": "aws_s3_bucket"},
	    {"resource_id": "mid", "resource_type": "aws_s3_bucket"}
	  ], "edges": [
	    {"source": "zeta", "target": "hub"},
	    {"source": "hub", "target": "alpha"},
	    {"source": "mid", "target": "hub"}
	  ]}`)

	first, _, _ := BuildGraphContextForHunter(graph, fixtureAbsent, []string{"iam"})
	want := strings.Join([]string{
		"RELEVANT RESOURCES:",
		"  - hub (aws_iam_role) @ None",
		"    Config: None",
		"",
		"CONNECTED RESOURCES (1-hop neighbors):",
		"  - zeta (aws_s3_bucket) @ None",
		"    Config: None",
		"  - alpha (aws_s3_bucket) @ None",
		"    Config: None",
		"  - mid (aws_s3_bucket) @ None",
		"    Config: None",
	}, "\n")
	if first != want {
		t.Fatalf("neighbor block\n--- got ---\n%s\n--- want ---\n%s", first, want)
	}
	for i := 0; i < 50; i++ {
		again, _, _ := BuildGraphContextForHunter(graph, fixtureAbsent, []string{"iam"})
		if again != first {
			t.Fatalf("neighbor order is not stable across runs:\n%s\nvs\n%s", first, again)
		}
	}
}

