// Contract items 1-4 and 6: everything except the expression rendering must be
// identical to what the Python parser produced for the same fixture.
func TestParseTerraformDirectory_MatchesPythonOnVulnerableInfra(t *testing.T) {
	got, _, _, _ := parseFixture(t, vulnerableInfraFixture)
	want := loadPythonFixture(t, pythonInventoryFixture)

	assertSameKeyOrder(t, "$", got, want)

	gotRes := sectionOf(t, got, "resources")
	wantRes := sectionOf(t, want, "resources")
	if len(gotRes) != len(wantRes) {
		t.Fatalf("resource count = %d, Python = %d", len(gotRes), len(wantRes))
	}

	for i := range wantRes {
		g, w := asObject(t, gotRes[i]), asObject(t, wantRes[i])
		assertSameKeyOrder(t, "resources[%d]", g, w, i)
		// Identity fields must match exactly.
		for _, field := range []string{"id", "type", "name", "provider", "file_path", "line_number"} {
			gv, _ := g.Get(field)
			wv, _ := w.Get(field)
			if !reflect.DeepEqual(gv, wv) {
				t.Errorf("resources[%d].%s = %#v, Python = %#v", i, field, gv, wv)
			}
		}
		// Config: same keys in the same order; same VALUES wherever Python
		// produced something other than a pyhcl2 AST repr.
		gcfg, _ := g.Get("config")
		wcfg, _ := w.Get("config")
		id, _ := g.Get("id")
		compareIgnoringReprs(t, "resources["+pyfmt.Str(id)+"].config", gcfg, wcfg)
	}

	// The non-resource sections have no non-constant expressions on this
	// fixture, so they must be byte-identical.
	for _, section := range []string{"variables", "outputs", "providers", "modules"} {
		gv, _ := got.Get(section)
		wv, _ := want.Get(section)
		if !reflect.DeepEqual(gv, wv) {
			t.Errorf("%s = %#v, Python = %#v", section, gv, wv)
		}
	}
}

// Contract items 1-4 again, on the fixture that covers every HCL expression
// KIND rather than only the ones the benchmark repo happens to use.
func TestParseTerraformDirectory_MatchesPythonOnExpressionFixture(t *testing.T) {
	got, _, _, _ := parseFixture(t, expressionsFixtureDir)
	want := loadPythonFixture(t, pythonExpressionsFixt)

	assertSameKeyOrder(t, "$", got, want)

	for _, section := range []string{"resources", "variables", "outputs", "providers", "modules"} {
		g := sectionOf(t, got, section)
		w := sectionOf(t, want, section)
		if len(g) != len(w) {
			t.Fatalf("%s: %d entries, Python = %d", section, len(g), len(w))
		}
		for i := range w {
			path := section + "[" + itoa(i) + "]"
			if section != "resources" {
				compareIgnoringReprs(t, path, g[i], w[i])
				continue
			}
			// references/referenced_by are DERIVED from the config strings, so
			// they inherit the expression-rendering divergence: Go sees the
			// real traversals Python's AST reprs hide. They are asserted as a
			// superset here and exactly in
			// TestParseTerraformDirectory_ReferencesOnVulnerableInfra.
			gr, wr := asObject(t, g[i]), asObject(t, w[i])
			assertSameKeyOrder(t, "%s", gr, wr, path)
			for _, kv := range wr {
				gv, present := gr.Get(kv.K)
				if !present {
					t.Errorf("%s.%s: missing in the Go output", path, kv.K)
					continue
				}
				if kv.K == "references" || kv.K == "referenced_by" {
					assertSuperset(t, path+"."+kv.K, stringsOf(gv), stringsOf(kv.V))
					continue
				}
				compareIgnoringReprs(t, path+"."+kv.K, gv, kv.V)
			}
		}
	}
}

// assertSuperset checks that Go still reports everything Python did — the
// expression-rendering divergence is additive, never subtractive.
func assertSuperset(t *testing.T, path string, got, want []string) {
	t.Helper()
	for _, w := range want {
		if !contains(got, w) {
			t.Errorf("%s: Go dropped %q, which Python reports (got %v)", path, w, got)
		}
	}
}

// The documented divergence, pinned so it cannot grow silently: these — and
// ONLY these — are the leaves where Python emits a pyhcl2 AST repr and Go emits
// the expression's source text.
