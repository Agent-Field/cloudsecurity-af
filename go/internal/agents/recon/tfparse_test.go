// Contract item 5, in isolation.
func TestExtractReferences(t *testing.T) {
	cases := []struct {
		name  string
		input any
		want  []string
	}{
		{"plain traversal", "aws_s3_bucket.b.arn", []string{"aws_s3_bucket.b"}},
		{"data traversal", "data.aws_ami.ubuntu.id", []string{"data.aws_ami.ubuntu"}},
		{
			"excluded namespaces",
			"var.x local.y each.key self.id count.index path.module terraform.workspace",
			[]string{},
		},
		{
			// Every namespace prefix is excluded by startswith, so a nested
			// var.-prefixed name is excluded too.
			"namespace prefix match is a prefix test",
			"var.something_long",
			[]string{},
		},
		{"uppercase is not a reference", "AWS_S3.Bucket", []string{}},
		{"digits may not lead", "1abc.def", []string{}},
		{"sorted and deduplicated", "b_x.y a_x.y b_x.y", []string{"a_x.y", "b_x.y"}},
		{"nested containers are walked", pyfmt.Ordered{
			{K: "a", V: []any{"aws_s3_bucket.one.id"}},
			{K: "b", V: pyfmt.Ordered{{K: "c", V: "aws_iam_role.two.arn"}}},
			{K: "d", V: 1},
			{K: "e", V: nil},
			{K: "f", V: true},
		}, []string{"aws_iam_role.two", "aws_s3_bucket.one"}},
		{
			// The literal-string quirk that makes Python report "t2.micro".
			"a dotted literal is indistinguishable from a reference",
			"t2.micro",
			[]string{"t2.micro"},
		},
		{
			// The regex stops at the second component, so a three-part
			// traversal contributes only "<type>.<name>".
			"three-part traversal yields two parts",
			"aws_s3_bucket.customer_data.arn",
			[]string{"aws_s3_bucket.customer_data"},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := extractReferences(tc.input); !reflect.DeepEqual(got, tc.want) {
				t.Errorf("extractReferences = %v, want %v", got, tc.want)
			}
		})
	}
}

// Contract item 1: pathlib ordering is component-wise, and rglob does not skip
// dot-directories.
func TestTerraformFiles_PathlibOrderAndHiddenDirectories(t *testing.T) {
	root := t.TempDir()
	for _, rel := range []string{
		"probe.tf", "sub/s.tf", ".hidden/h.tf", "_under/u.tf",
		"a-b/c.tf", "a/b.tf", "not-terraform.txt", "deep/er/x.tf",
	} {
		full := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o777); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte("# tf\n"), 0o666); err != nil {
			t.Fatal(err)
		}
	}

	got, err := terraformFiles(root)
	if err != nil {
		t.Fatalf("terraformFiles: %v", err)
	}
	// sorted(Path(root).rglob("*.tf")) on Python 3.11 — component-wise, so
	// "a/b.tf" precedes "a-b/c.tf" even though the raw strings sort the other
	// way ('-' < '/').
	want := []string{
		".hidden/h.tf",
		"_under/u.tf",
		"a/b.tf",
		"a-b/c.tf",
		"deep/er/x.tf",
		"probe.tf",
		"sub/s.tf",
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("terraformFiles = %v\n                want %v", got, want)
	}
}

