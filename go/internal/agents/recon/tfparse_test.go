// TestParseTerraformDirectory_ParserAcceptanceDivergesFromPyhcl2 pins the
// whole-file divergence documented on ParseTerraformDirectory.
//
// Both nodes skip a .tf file their parser rejects, but the two parsers disagree
// about WHICH files those are. Measured against pyhcl2 in the repo venv:
//
//	parse_file("resource \"a\" \"b\" { p = 1e3 }")     -> DiagnosticError
//	parse_file("resource \"a\" \"b\" { p = 1E3 }")     -> DiagnosticError
//	parse_file("resource \"a\" \"b\" { p = 1.5e-3 }")  -> DiagnosticError
//	parse_file("resource \"a\" \"b\" { p = 1000 }")    -> OK
//
// so for the exponent files Python emits an EMPTY inventory while Go emits the
// resource. Go is the better behaviour (the spellings are valid HCL); this test
// exists so the divergence is a recorded, deliberate one rather than something
// a reviewer diffing two inventories has to rediscover.
func TestParseTerraformDirectory_ParserAcceptanceDivergesFromPyhcl2(t *testing.T) {
	for _, literal := range []string{"1e3", "1E3", "1.5e-3"} {
		root := t.TempDir()
		src := "resource \"aws_s3_bucket\" \"b\" {\n  p = " + literal + "\n}\n"
		if err := os.WriteFile(filepath.Join(root, "main.tf"), []byte(src), 0o666); err != nil {
			t.Fatal(err)
		}
		_, total, _, err := ParseTerraformDirectory(root, t.TempDir())
		if err != nil {
			t.Fatalf("%s: %v", literal, err)
		}
		if total != 1 {
			t.Errorf("p = %s -> total = %d, want 1 (hclsyntax accepts exponents; "+
				"pyhcl2 rejects them and Python drops the whole file)", literal, total)
		}
	}
}
