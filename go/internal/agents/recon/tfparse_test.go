func assertSameKeyOrder(t *testing.T, format string, got, want pyfmt.Ordered, args ...any) {
	t.Helper()
	gk := make([]string, len(got))
	for i, kv := range got {
		gk[i] = kv.K
	}
	wk := make([]string, len(want))
	for i, kv := range want {
		wk[i] = kv.K
	}
	if !reflect.DeepEqual(gk, wk) {
		t.Errorf(format+": key order = %v, Python = %v", append(args, gk, wk)...)
	}
}

// compareIgnoringReprs asserts Go and Python agree everywhere except at the
// leaves where Python emitted a pyhcl2 AST repr.
func compareIgnoringReprs(t *testing.T, path string, got, want any) {
	t.Helper()
	if s, ok := want.(string); ok && strings.Contains(s, pyhcl2ReprMarker) {
		return // documented divergence; pinned separately
	}
	switch w := want.(type) {
	case pyfmt.Ordered:
		g, ok := got.(pyfmt.Ordered)
		if !ok {
			t.Errorf("%s: Go value is %T, Python has an object", path, got)
			return
		}
		assertSameKeyOrder(t, "%s", g, w, path)
		for _, kv := range w {
			gv, present := g.Get(kv.K)
			if !present {
				t.Errorf("%s.%s: missing in the Go output", path, kv.K)
				continue
			}
			compareIgnoringReprs(t, path+"."+kv.K, gv, kv.V)
		}
	case []any:
		g, ok := got.([]any)
		if !ok {
			t.Errorf("%s: Go value is %T, Python has a list", path, got)
			return
		}
		if len(g) != len(w) {
			t.Errorf("%s: %d elements, Python has %d", path, len(g), len(w))
			return
		}
		for i := range w {
			compareIgnoringReprs(t, path+"["+itoa(i)+"]", g[i], w[i])
		}
	default:
		if !reflect.DeepEqual(got, want) {
			t.Errorf("%s = %#v, Python = %#v", path, got, want)
		}
	}
}

// collectReprPaths records every leaf of the Python fixture whose value is a
// pyhcl2 AST repr.
func collectReprPaths(out *[]string, path string, v any) {
	switch x := v.(type) {
	case pyfmt.Ordered:
		for _, kv := range x {
			child := kv.K
			if path != "" {
				child = path + "." + kv.K
			}
			collectReprPaths(out, child, kv.V)
		}
	case []any:
		for i, item := range x {
			collectReprPaths(out, path+"["+itoa(i)+"]", item)
		}
	case string:
		if strings.Contains(x, pyhcl2ReprMarker) {
			*out = append(*out, path)
		}
	}
}

// lookupPath resolves a dotted/indexed path produced by collectReprPaths.
func lookupPath(t *testing.T, root pyfmt.Ordered, path string) any {
	t.Helper()
	var cur any = root
	for _, seg := range strings.Split(path, ".") {
		name, indices := splitIndices(seg)
		if name != "" {
			obj, ok := cur.(pyfmt.Ordered)
			if !ok {
				t.Fatalf("%s: %q is not an object", path, name)
			}
			v, present := obj.Get(name)
			if !present {
				t.Fatalf("%s: key %q missing", path, name)
			}
			cur = v
		}
		for _, idx := range indices {
			list, ok := cur.([]any)
			if !ok || idx >= len(list) {
				t.Fatalf("%s: index %d out of range", path, idx)
			}
			cur = list[idx]
		}
	}
	return cur
}

func splitIndices(seg string) (string, []int) {
	open := strings.IndexByte(seg, '[')
	if open < 0 {
		return seg, nil
	}
	name := seg[:open]
	var indices []int
	rest := seg[open:]
	for len(rest) > 0 && rest[0] == '[' {
		close := strings.IndexByte(rest, ']')
		if close < 0 {
			break
		}
		n := 0
		for _, c := range rest[1:close] {
			n = n*10 + int(c-'0')
		}
		indices = append(indices, n)
		rest = rest[close+1:]
	}
	return name, indices
}

func stringsOf(v any) []string {
	items, ok := v.([]any)
	if !ok {
		return nil
	}
	out := make([]string, 0, len(items))
	for _, it := range items {
		if s, ok := it.(string); ok {
			out = append(out, s)
		}
	}
	return out
}

func contains(haystack []string, needle string) bool {
	for _, s := range haystack {
		if s == needle {
			return true
		}
	}
	return false
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var buf [20]byte
	i := len(buf)
	for n > 0 {
		i--
		buf[i] = byte('0' + n%10)
		n /= 10
	}
	return string(buf[i:])
}

// TestParseTerraformDirectory_IntegerLiteralsKeepPythonsExactDigits pins the
// arbitrary-precision half of Python's int.
//
// pyhcl2 evaluates an integer literal into `Integer._raw`, a Python int, and
// `json.dump` writes its exact digits however large it is. Ground truth from
// the repo venv on this exact fixture:
//
//	"big_port": 12345678901234567890,
//	"edge_hi":  9223372036854775807,
//	"edge_ovr": 9223372036854775808,
//	"small":    5432,
//	"floaty":   1.5
//
// Converting through float64 (what `bf.Float64()` does) wrote
// 1.2345678901234567e+19 and 9.223372036854776e+18 instead — and because
// "port" is a configSummaryKeywords match, the lossy value also reached
// graph.json's config_summary and the hunter prompt's `Config: {...}` line.
func TestParseTerraformDirectory_IntegerLiteralsKeepPythonsExactDigits(t *testing.T) {
	root := t.TempDir()
	src := `resource "aws_s3_bucket" "b" {
  bucket   = "x"
  big_port = 12345678901234567890
  edge_hi  = 9223372036854775807
  edge_ovr = 9223372036854775808
  small    = 5432
  floaty   = 1.5
}
`
	if err := os.WriteFile(filepath.Join(root, "main.tf"), []byte(src), 0o666); err != nil {
		t.Fatal(err)
	}

	out := t.TempDir()
	path, _, _, err := ParseTerraformDirectory(root, out)
	if err != nil {
		t.Fatalf("ParseTerraformDirectory: %v", err)
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read inventory.json: %v", err)
	}
	text := string(raw)
	for _, want := range []string{
		`"big_port": 12345678901234567890`,
		`"edge_hi": 9223372036854775807`,
		`"edge_ovr": 9223372036854775808`,
		`"small": 5432`,
		`"floaty": 1.5`,
	} {
		if !strings.Contains(text, want) {
			t.Errorf("inventory.json is missing %s\ngot:\n%s", want, text)
		}
	}
	if strings.Contains(text, "e+19") || strings.Contains(text, "e+18") {
		t.Errorf("an integer literal was written as a float:\n%s", text)
	}

	// The read side has to agree, or the value degrades on its way into
	// graph.json's config_summary and the hunter prompt.
	reloaded, err := pyfmt.Load(raw)
	if err != nil {
		t.Fatalf("pyfmt.Load: %v", err)
	}
	config := configOfFirstResource(t, reloaded)
	big, _ := config.Get("big_port")
	if got := pyfmt.Repr(big); got != "12345678901234567890" {
		t.Errorf("repr(config[\"big_port\"]) = %s, want the exact digits", got)
	}
	if got := pyfmt.Dumps(config, 0); !strings.Contains(got, `"big_port": 12345678901234567890`) {
		t.Errorf("re-dumping the loaded config lost the digits: %s", got)
	}
}

