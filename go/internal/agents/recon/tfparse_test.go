// VALIDATION CONTRACT for ParseTerraformDirectory (from parse_terraform_directory
// in src/cloudsecurity_af/agents/recon/_terraform_parser.py, expressed in terms
// of observable behavior rather than of the Go code):
//
//  1. Every *.tf under the repo is parsed, in pathlib sort order, and its path is
//     recorded RELATIVE to the repo.
//  2. `resource` blocks with >=2 labels produce {id "<type>.<name>", type, name,
//     provider, file_path, line_number 0, config, references, referenced_by};
//     `data` blocks produce the same with id "data.<type>.<name>" and type
//     "data.<type>".
//  3. `variable`, `output`, `provider` and `module` blocks produce their own
//     records with the exact key sets Python emits, including the str()-vs-raw
//     asymmetries (variable.type/default are str()-ed, variable.description is
//     not; output.value is str()-ed with "" for a missing value;
//     provider.version is ALWAYS null).
//  4. `provider` is _PROVIDER_MAP[type prefix] or the prefix itself.
//  5. `references` is the sorted, de-duplicated set of resource-shaped tokens
//     found in any string in the config, minus the var./local./each./self./
//     count./path./terraform. namespaces. `referenced_by` is its reverse index.
//  6. The file is inventory.json inside output_dir, written as
//     json.dump(..., indent=2, default=str).
//  7. An unparsable file is skipped, not fatal.
//  8. The return value is (path, len(resources), "terraform").
//
// The fixtures the assertions run against are generated by
// go/scripts/gen_golden.py from the REAL Python parser.

const (
	pythonInventoryFixture  = "testdata/python/inventory.json"
	pythonExpressionsFixt   = "testdata/python/expressions_inventory.json"
	pythonSummaryFixture    = "testdata/python/summary.json"
	vulnerableInfraFixture  = "testdata/vulnerable_infra"
	expressionsFixtureDir   = "testdata/expressions"
	pyhcl2ReprMarker        = "SourceSpan("
	pythonTreeInfraRelative = "../../../../tests/fixtures/vulnerable_infra/main.tf"
)

// parseFixture runs the Go parser over dir and returns the decoded inventory.
func parseFixture(t *testing.T, dir string) (inv pyfmt.Ordered, path string, total int, iacType string) {
	t.Helper()
	out := t.TempDir()
	path, total, iacType, err := ParseTerraformDirectory(dir, out)
	if err != nil {
		t.Fatalf("ParseTerraformDirectory(%q): %v", dir, err)
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}
	decoded, err := pyfmt.Load(raw)
	if err != nil {
		t.Fatalf("decoding %s: %v", path, err)
	}
	obj, ok := decoded.(pyfmt.Ordered)
	if !ok {
		t.Fatalf("inventory.json decoded as %T, want an object", decoded)
	}
	return obj, path, total, iacType
}

